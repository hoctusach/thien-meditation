"""quotes.json -> quotes.js (what the app loads). Run after editing quotes.json or adding/removing voice files.
quotes.json: [{id, vi?, en?, author, source}] — a quote may have only one language. `id` is stable (never reuse/renumber).
Voices: audio/q/<lang>_<id>.mp3 (e.g. audio/q/vi_q0001.mp3, audio/q/en_q0001.mp3). A line with no voice file is not played yet;
as soon as its file exists and this script is run, it joins the same random order as the affirmations.
Output has "vo": ["vi","en"] listing the languages that have a voice file. Then run tools/build_sw.py."""
import json, os
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(root)
Q = json.load(open("quotes.json", encoding="utf-8"))
ids = [q["id"] for q in Q]
assert len(ids) == len(set(ids)), "duplicate ids"
out, have, missing = [], {"vi": 0, "en": 0}, {"vi": 0, "en": 0}
for q in Q:
    assert q.get("vi") or q.get("en"), q["id"] + ": no text"
    o = {"id": q["id"]}
    for lang in ("vi", "en"):
        if q.get(lang):
            o[lang] = q[lang]
            if os.path.exists(f"audio/q/{lang}_{q['id']}.mp3"): o.setdefault("vo", []).append(lang); have[lang] += 1
            else: missing[lang] += 1
    o["author"] = q.get("author", "")
    out.append(o)
body = ",\n".join(" " + json.dumps(o, ensure_ascii=False) for o in out)
open("quotes.js", "w", encoding="utf-8").write(
    "// Quote library — generated by tools/build_quotes.py from quotes.json + audio/q/*.mp3. Do not edit.\n"
    "window.QUOTES = [\n" + body + "\n];\nwindow.__thienJS = (window.__thienJS || 0) + 1;\n")
print(f"{len(Q)} quotes · voiced vi {have['vi']} en {have['en']} · waiting for voice vi {missing['vi']} en {missing['en']}")
