"""Synthesise the bell sounds (additive modal synthesis, numpy) -> audio/bells/*.mp3
Shipped: audio/bells/thien.mp3 = "Chuông thiền" 3 strikes (0 / 10 / 20 s, ~34 s) and audio/bell5.mp3 = the same file
(daily reminder); audio/bells/bells.json. Re-running reproduces them byte for byte (same ffmpeg build).
SAMPLES=1 also writes listening samples of all bells (1 and 3 strikes) to samples/bells/ (not shipped).

"thien" (Chuông thiền) is RE-SYNTHESISED from measurements of a reference meditation bell
(mode frequencies, levels and per-mode decay were measured; no audio from the reference is used
or shipped). All sounds are generated by this script: no third-party samples, no licence limits.
"""
import numpy as np, subprocess, os, json
SR = 48000
os.chdir(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

# Measured modes of the reference strike: (Hz, level dB averaged over 0.03-2.03 s, decay dB/s)
# Close pairs (430.5/439.5, 825.5/834, 1884/1889.5) are the bell's natural split modes -> gentle
# ~9 Hz shimmer exactly like the real bell (no added vibrato / LFO).
THIEN_MODES = [
    (150.0,  -5.5, -2.38), (299.5, -39.5, -2.43),
    (430.5,  -4.5, -1.01), (439.5,  -7.7, -0.97), (416.5, -39.7, -0.97), (454.0, -41.5, -1.35),
    (589.0, -36.9, -3.88),
    (825.5,  -4.9, -1.95), (834.0, -17.7, -1.95), (861.5, -31.3, -2.94), (879.0, -25.5, -2.49),
    (1256.0, -32.9, -3.76), (1265.0, -31.5, -3.73),
    (1316.0,  0.0, -4.05), (1307.5, -37.7, -4.04), (1325.0, -36.2, -4.05),
    (1884.0, -26.5, -4.76), (1889.5, -19.1, -4.76),
    (2146.0, -37.7, -6.55), (2529.5, -28.5, -7.52), (3212.0, -35.6, -18.7),
]

def modal(modes, length, pitch=1.0, decay_scale=1.0, attack=0.0046, mallet_db=-34, seed=3):
    t = np.arange(int(SR * length)) / SR
    rng = np.random.default_rng(seed)
    win = np.hanning(2 * SR); tw = 0.03 + np.arange(2 * SR) / SR
    y = np.zeros_like(t)
    for hz, lev, slope in modes:
        s = slope / decay_scale
        w = (win * 10 ** (s * tw / 20)).sum() / win.sum()     # undo the averaging of the measurement
        a0 = 10 ** (lev / 20) / w
        y += a0 * np.sin(2 * np.pi * hz * pitch * t + rng.uniform(0, 2 * np.pi)) * 10 ** (s * t / 20)
    y *= 0.5 - 0.5 * np.cos(np.pi * np.clip(t / attack, 0, 1))    # 4.6 ms rise, like a wooden striker
    n = rng.standard_normal(len(t)) * np.exp(-t / 0.006)          # tiny "tok" of the striker
    k = np.exp(-np.arange(48) / 8.0); n = np.convolve(n, k / k.sum(), mode="same")
    y += n * np.abs(y).max() * 10 ** (mallet_db / 20) * 4
    return y / np.abs(y).max()

def strike(f0, partials, length, attack=0.002, seed=1):
    t = np.arange(int(SR * length)) / SR; y = np.zeros_like(t); rng = np.random.default_rng(seed)
    for r, a, d in partials:
        y += a * np.sin(2 * np.pi * f0 * r * t + rng.uniform(0, 2 * np.pi)) * np.exp(-t / d)
    y *= 1 - np.exp(-t / attack)
    return y / np.abs(y).max()

BELLS = {
  # id: (Vietnamese, English, generator, lowpass Hz, single length s, x5 gap s)
  "thien": ("Chuông thiền", "Meditation bell", lambda: modal(THIEN_MODES, 14), 9000, 14, 8.0),
  "thien-tram": ("Chuông thiền trầm", "Deep meditation bell",
                 lambda: modal(THIEN_MODES, 16, pitch=2 ** (-3 / 12), decay_scale=1.15, seed=5), 8000, 16, 9.0),
  "bright": ("Chuông sáng (ngắn)", "Bright short chime", lambda: strike(432, [
      (2, 1.0, 0.6), (5.4, .05 / .13, 1.6 / 5.0), (8.9, .025 / .13, .9 / 5.0)], 4), 12000, 4, 3.5),
}
DEFAULT = "thien"

def encode(y, path, lp, fade_at, fade=2.5, target=-24.0):
    """Linear gain to ~-24 LUFS (no dynamic compression, so the natural decay is kept), peak <= -3 dBFS."""
    pcm = (np.clip(y, -1, 1) * 32767).astype(np.int16).tobytes()
    pre = f"lowpass=f={lp},afade=t=out:st={fade_at:.2f}:d={fade}"
    inp = ["ffmpeg", "-y", "-hide_banner", "-f", "s16le", "-ar", str(SR), "-ac", "1", "-i", "-"]
    m = subprocess.run(inp + ["-af", pre + ",loudnorm=print_format=json", "-f", "null", "-"], input=pcm,
                       capture_output=True, check=True).stderr.decode()
    j = json.loads(m[m.rindex("{"):m.rindex("}") + 1])
    gain = min(target - float(j["input_i"]), -3.0 - float(j["input_tp"]))
    subprocess.run(inp[:2] + ["-loglevel", "error"] + inp[2:] + ["-af", pre + f",volume={gain:.2f}dB",
                    "-ar", "44100", "-b:a", "64k", path], input=pcm, check=True)

def repeat(one, n, gap):
    out = np.zeros(int(SR * (gap * (n - 1))) + len(one))
    for k in range(n):
        s = int(k * gap * SR); out[s:s + len(one)] += one
    return out / np.abs(out).max()

SHIPPED = ["thien"]          # bells the app uses
STRIKES, STRIKE_GAP = 3, 10.0  # app bell: 3 strikes, 10 s apart (app.js waits BELL_CLEAR_MS = 23 s after it)

if __name__ == "__main__":
    import glob, shutil
    os.makedirs("audio/bells", exist_ok=True)
    for f in glob.glob("audio/bells/*.mp3"): os.remove(f)
    meta = []
    for bid in SHIPPED:
        vi, en, gen, lp, L, gap = BELLS[bid]
        three = repeat(gen(), STRIKES, STRIKE_GAP)
        encode(three, f"audio/bells/{bid}.mp3", lp, len(three) / SR - 2.5)
        meta.append({"id": bid, "vi": vi, "en": en})
        print(bid, STRIKES, "strikes,", round(len(three) / SR, 1), "s")
    shutil.copy(f"audio/bells/{DEFAULT}.mp3", "audio/bell5.mp3")
    open("audio/bells/bells.json", "w").write(json.dumps(meta, ensure_ascii=False) + "\n")
    if os.environ.get("SAMPLES"):          # listening samples (not precached / not part of the app)
        os.makedirs("samples/bells", exist_ok=True)
        for f in glob.glob("samples/bells/*.mp3"): os.remove(f)
        for i, (bid, name) in enumerate([("thien", "chuong-thien"), ("thien-tram", "chuong-thien-tram"), ("bright", "chuong-sang-ngan")], 1):
            vi, en, gen, lp, L, gap = BELLS[bid]; one = gen()
            encode(one, f"samples/bells/{i}-{name}.mp3", lp, L - 2.5)
            three = repeat(one, 3, 10.0 if bid != "bright" else 3.5)
            encode(three, f"samples/bells/{i}-{name}-3-hoi.mp3", lp, len(three) / SR - 2.5)
